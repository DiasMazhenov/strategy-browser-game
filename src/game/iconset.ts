// ─────────────────────────────────────────────────────────────────────────────
// СТРОКИ С ТОКЕНАМИ: «+12 {i:wood}» → сегменты текст/иконка.
// Один формат для React (<RT/>) и canvas (drawRich) — эмодзи больше не нужны.
// ─────────────────────────────────────────────────────────────────────────────
export type RichSeg = { t: 'txt'; s: string } | { t: 'ico'; n: string };
const TOK = /\{i:([a-z0-9_]+)\}/g;

export function parseRich(text: string): RichSeg[] {
  const out: RichSeg[] = [];
  let last = 0;
  TOK.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = TOK.exec(text))) {
    if (m.index > last) out.push({ t: 'txt', s: text.slice(last, m.index) });
    out.push({ t: 'ico', n: iconName(m[1]) });
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push({ t: 'txt', s: text.slice(last) });
  return out;
}
export const hasTokens = (text: string) => TOK.test(text) || text.includes('{i:');
/** для нативных title/alt: токены → короткий текст или пусто */
export function plainRich(text: string): string {
  return text.replace(TOK, '').replace(/\s{2,}/g, ' ').trim();
}

// ─────────────────────────────────────────────────────────────────────────────
// CANVAS: рисуем иконку и богатый текст (текст + иконки в одной строке).
// ─────────────────────────────────────────────────────────────────────────────
const pathCache = new Map<string, Path2D>();
function partPath(part: IconPart): Path2D {
  let p = pathCache.get(part.d);
  if (!p) { p = new Path2D(part.d); pathCache.set(part.d, p); }
  return p;
}
const VB = 24;

/** нарисовать иконку: (x,y) — левый верх квадрата size×size */
export function drawIcon(ctx: CanvasRenderingContext2D, name: string, x: number, y: number, size: number, color: string) {
  const def = iconDef(name);
  const k = size / VB;
  ctx.save();
  ctx.translate(x, y);
  ctx.scale(k, k);
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  for (const part of def.parts) {
    const p = partPath(part);
    const fill = part.f === 'cur' ? color : part.f;
    const stroke = part.s === 'cur' ? color : (part.s ?? color);
    if (fill) { ctx.fillStyle = fill; ctx.fill(p); }
    // Обводка задана в единицах viewBox (24) и масштабируется вместе с иконкой:
    // на 10-px иконке она становилась 0.7 px и растворялась, на 22-px — толстела.
    // Держим на экране не тоньше 1.1 px (в единицах viewBox — 1.1/k).
    if (part.s !== 'none') { ctx.strokeStyle = stroke; ctx.lineWidth = Math.max(part.w ?? 1.7, 1.1 / k); ctx.stroke(p); }
  }
  ctx.restore();
}

/** ширина строки с токенами при заданном размере шрифта (иконка = 1.05em) */
export function measureRich(ctx: CanvasRenderingContext2D, text: string, iconSize: number): number {
  let w = 0;
  for (const seg of parseRich(text)) {
    if (seg.t === 'txt') w += ctx.measureText(seg.s).width;
    else w += iconSize + iconSize * 0.12;
  }
  return w;
}

/** нарисовать строку с токенами; (x,y) учитывает текущий textAlign/baseline */
export function drawRich(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, iconSize: number) {
  const segs = parseRich(text);
  const total = measureRich(ctx, text, iconSize);
  const align = ctx.textAlign;
  let cx = x;
  if (align === 'center') cx = x - total / 2;
  else if (align === 'right' || align === 'end') cx = x - total;
  const prevAlign = ctx.textAlign;
  ctx.textAlign = 'left';
  for (const seg of segs) {
    if (seg.t === 'txt') {
      ctx.fillStyle = color;
      ctx.fillText(seg.s, cx, y);
      cx += ctx.measureText(seg.s).width;
    } else {
      const base = ctx.textBaseline;
      const dy = base === 'middle' ? y - iconSize / 2
        : base === 'top' || base === 'hanging' ? y
        : y - iconSize * 0.86;   // alphabetic: иконка сидит на базовой линии
      drawIcon(ctx, seg.n, cx, dy, iconSize, color);
      cx += iconSize + iconSize * 0.12;
    }
  }
  ctx.textAlign = prevAlign;
}
/** обводка-подложка для богатого текста (как strokeText для обычного) */
export function strokeRich(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, iconSize: number) {
  const segs = parseRich(text);
  const total = measureRich(ctx, text, iconSize);
  const align = ctx.textAlign;
  let cx = x;
  if (align === 'center') cx = x - total / 2;
  else if (align === 'right' || align === 'end') cx = x - total;
  const prevAlign = ctx.textAlign;
  ctx.textAlign = 'left';
  for (const seg of segs) {
    if (seg.t === 'txt') { ctx.strokeText(seg.s, cx, y); cx += ctx.measureText(seg.s).width; }
    else cx += iconSize + iconSize * 0.12;
  }
  ctx.textAlign = prevAlign;
}
